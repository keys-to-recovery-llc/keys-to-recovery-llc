/* Keys to Recovery LLC — service worker.
   Strategy: network-first for page navigations (fresh content, cache
   fallback when offline), cache-first for static assets. /api/* is never
   intercepted. Registered by the frontend (see MIGRATION.md hand-off
   notes) — keep the registration snippet in sync with CACHE_NAME bumps. */

const CACHE_NAME = 'ktr-static-v1';
const PRECACHE = [
  '/manifest.json',
  '/favicon.png',
  '/logo-full.png',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png',
  '/icons/apple-touch-icon.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return; // API: always live

  if (request.mode === 'navigate') {
    // Network-first for pages; fall back to cache, then to the SPA shell.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put('/', copy));
          return response;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE_NAME);
          return (await cache.match(request)) || (await cache.match('/')) || Response.error();
        }),
    );
    return;
  }

  // Cache-first for static assets (icons, images, fonts, built JS/CSS).
  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
